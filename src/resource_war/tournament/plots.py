def fig_h2(results: Path, out: Path) -> Path:
    data = json.loads((results / "H2_summary.json").read_text(encoding="utf-8"))
    depths = sorted(data["depths"], key=int)
    fig, ax = plt.subplots(figsize=(6, 3.2))
    width = 0.36
    for k, (key, label) in enumerate((("win_rate", "win rate"), ("tie_rate", "tie rate"))):
        xs = [i + (k - 0.5) * width for i in range(len(depths))]
        ivs = [data["depths"][d][key] for d in depths]
        est = [iv["estimate"] for iv in ivs]
        ax.bar(xs, est, width=width - 0.03, color=SERIES[k], label=label, edgecolor=SURFACE, linewidth=1)
        ax.errorbar(xs, est, yerr=list(zip(*[_err(iv) for iv in ivs])), fmt="none", ecolor=TEXT_2, elinewidth=1, capsize=3)
    ax.set_xticks(range(len(depths)), [f"depth {d}" for d in depths])
    ax.set_ylim(0, 1)
    ax.set_ylabel(f"Share of battles vs a depth-{data['opponent_depth']} opponent")
    ax.set_title("H2: Battle Mode results by search depth (Wilson 95% CI)")
    ax.legend(loc="upper left")
    ax.grid(axis="x", visible=False)
    path = out / "fig_h2_battle_depth.png"
    fig.savefig(path)
    plt.close(fig)
    return path


def fig_e3(verdicts: dict, out: Path) -> Path:
    by_depth = verdicts["H1"]["by_depth"]
    depths = sorted(by_depth, key=int)
    fig, ax = plt.subplots(figsize=(6, 3.2))
    for k, (key, label) in enumerate((("mean_minimax_nodes", "plain minimax"), ("mean_alphabeta_nodes", "alpha-beta"))):
        ys = [by_depth[d][key] for d in depths]
        ax.plot([int(d) for d in depths], ys, color=SERIES[k], linewidth=2, marker="o", markersize=6, label=label)
        ax.annotate(f"{ys[-1]:,.0f}", (int(depths[-1]), ys[-1]), textcoords="offset points", xytext=(6, -3), color=TEXT_2, fontsize=8)
    ax.set_yscale("log")
    ax.set_xticks([int(d) for d in depths])
    ax.set_xlabel("Search depth (plies)")
    ax.set_ylabel("Mean nodes per decision (log scale)")
    ax.set_title("E3: nodes searched on the frozen 500-position benchmark")
    ax.legend(loc="upper left")
    path = out / "fig_e3_nodes.png"
    fig.savefig(path)
    plt.close(fig)
    return path


def fig_e4(results: Path, out: Path) -> Path:
    pairs = json.loads((results / "E4_summary.json").read_text(encoding="utf-8"))["pairs"]
    fig, axes = plt.subplots(1, len(pairs), figsize=(3.0 * len(pairs), 3.0), sharey=True, squeeze=False)
    width = 0.26
    for ax, p in zip(axes[0], pairs):
        for k, (key, label) in enumerate((("symmetric_mix_float", "equal depths (p = 1/2)"), ("deep_mix_float", f"deeper (d={p['deep']})"), ("shallow_mix_float", f"shallower (d={p['shallow']})"))):
            xs = [i + (k - 1) * width for i in range(3)]
            ax.bar(xs, p[key], width=width - 0.03, color=SERIES[k], label=label, edgecolor=SURFACE, linewidth=1)
        ax.set_xticks(range(3), ["Attack", "Defend", "Expand"])
        ax.set_title(f"depth {p['deep']} vs {p['shallow']}", fontsize=9)
        ax.grid(axis="x", visible=False)
    axes[0][0].set_ylabel("Equilibrium probability at V = 6")
    handles = [plt.Rectangle((0, 0), 1, 1, color=SERIES[k]) for k in range(3)]
    fig.legend(handles, ["equal depths (configured p = 1/2)", "deeper player", "shallower player"], loc="lower center", bbox_to_anchor=(0.5, -0.06), ncol=3)
    fig.suptitle("E4: coupled encounter game, equilibrium mixes", color=TEXT, fontsize=11)
    path = out / "fig_e4_coupling.png"
    fig.savefig(path)
    plt.close(fig)
    return path


def fig_e5(results: Path, out: Path) -> Path:
    import csv

    with (results / "E5_value_sweep.csv").open(encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    vs = [float(r["V"]) for r in rows]
    fig, (top, bottom) = plt.subplots(2, 1, figsize=(6.5, 5), sharex=True, gridspec_kw={"height_ratios": [3, 2]})
    for k, (key, label) in enumerate((("selected_A", "Attack"), ("selected_D", "Defend"), ("selected_E", "Expand"))):
        top.plot(vs, [float(r[key]) for r in rows], color=SERIES[k], linewidth=2, marker="o", markersize=4, label=label)
    for ax in (top, bottom):
        ax.axvline(4, color=TEXT_2, linewidth=1)
    top.annotate("V = 2c: degenerate edge", (4, 0.93), textcoords="offset points", xytext=(5, 0), color=TEXT_2, fontsize=8)
    top.set_ylabel("Selected equilibrium probability")
    top.set_title("E5: encounter-game equilibrium as the cell value V varies (c = 2, d = 1)")
    top.legend(loc="center right")
    bottom.plot(vs, [float(r["value"]) for r in rows], color=SERIES[0], linewidth=2, marker="o", markersize=4)
    bottom.plot(vs, [v / 2 for v in vs], color=TEXT_2, linewidth=1)
    bottom.annotate("(E,E) payoff V/2", (vs[-1], vs[-1] / 2), textcoords="offset points", xytext=(-80, 6), color=TEXT_2, fontsize=8)
    bottom.annotate("equilibrium payoff", (vs[-1], float(rows[-1]["value"])), textcoords="offset points", xytext=(-95, -30), color=TEXT_2, fontsize=8)
    bottom.set_xlabel("Cell value V")
    bottom.set_ylabel("Payoff per player")
    path = out / "fig_e5_value_sweep.png"
    fig.savefig(path)
    plt.close(fig)
    return path


def make_all(results: Path, out: Path) -> list[Path]:
    _style()
    out.mkdir(parents=True, exist_ok=True)
    verdicts = json.loads((results / "verdicts.json").read_text(encoding="utf-8"))
    return [fig_e1(results, out), fig_h4(results, out), fig_e2(results, out), fig_h2(results, out), fig_e3(verdicts, out), fig_e4(results, out), fig_e5(results, out)]
