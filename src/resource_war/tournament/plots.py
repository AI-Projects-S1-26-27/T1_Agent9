"""Report figures, drawn only from the result files in experiments/results.

Owner: Manas Tripathi, Reviewer: Jainam Parekh Naresh

Every figure shows uncertainty: error bars are the 95% intervals computed in
experiments.py (Wilson for rates, cluster bootstrap for differences). Every
figure has a matching table generated by tables.py, so no number is
available only as a picture.

Style rules (validated categorical palette, first three slots only):
- one y-axis per panel, never two scales;
- thin bars and hairline solid gridlines;
- labels in text colours, never in the series colour;
- a legend whenever a panel has two or more series.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

SERIES = ["#2a78d6", "#eb6834", "#1baf7a"]  # validated: all-pairs CVD dE >= 9.2 (light surface)
SURFACE = "#fcfcfb"
TEXT = "#0b0b0b"
TEXT_2 = "#52514e"
GRID = "#e4e3df"


def _style() -> None:
    plt.rcParams.update(
        {
            "figure.facecolor": SURFACE,
            "axes.facecolor": SURFACE,
            "axes.edgecolor": GRID,
            "axes.labelcolor": TEXT_2,
            "axes.titlecolor": TEXT,
            "axes.titlesize": 11,
            "axes.labelsize": 9,
            "xtick.color": TEXT_2,
            "ytick.color": TEXT_2,
            "xtick.labelsize": 8,
            "ytick.labelsize": 8,
            "axes.grid": True,
            "grid.color": GRID,
            "grid.linewidth": 0.8,
            "grid.linestyle": "-",
            "axes.axisbelow": True,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "legend.frameon": False,
            "legend.fontsize": 8,
            "font.size": 9,
            "savefig.dpi": 160,
            "savefig.bbox": "tight",
        }
    )


def _err(iv: dict) -> tuple[float, float]:
    return iv["estimate"] - iv["low"], iv["high"] - iv["estimate"]


def _hbar_diffs(ax, labels, intervals, color, xlabel) -> None:
    ys = list(range(len(labels)))[::-1]
    est = [iv["estimate"] for iv in intervals]
    lo = [_err(iv)[0] for iv in intervals]
    hi = [_err(iv)[1] for iv in intervals]
    ax.barh(ys, est, height=0.5, color=color, edgecolor=SURFACE, linewidth=2)
    ax.errorbar(est, ys, xerr=[lo, hi], fmt="none", ecolor=TEXT_2, elinewidth=1, capsize=3)
    ax.axvline(0, color=TEXT_2, linewidth=1)
    ax.set_yticks(ys, labels)
    ax.set_xlabel(xlabel)
    ax.grid(axis="y", visible=False)


def fig_e1(results: Path, out: Path) -> Path:
    data = json.loads((results / "E1_summary.json").read_text(encoding="utf-8"))
    pairs = data["pairings"]
    fig, ax = plt.subplots(figsize=(7, 3.2))
    _hbar_diffs(ax, [p["pairing"] for p in pairs], [p["mean_score_diff"] for p in pairs], SERIES[0], "Mean final-score difference (first named - second), 95% CI")
    ax.set_title("E1: round robin at battle depth 3")
    path = out / "fig_e1_score_diff.png"
    fig.savefig(path)
    plt.close(fig)
    return path


def fig_h4(results: Path, out: Path) -> Path:
    h4 = json.loads((results / "E1_summary.json").read_text(encoding="utf-8"))["h4"]
    series = [("eq_vs_fm", "Equilibrium - FixedMixed"), ("eq_vs_ph", "Equilibrium - PureHeuristic"), ("eu_vs_fm", "ExpectedUtility - FixedMixed")]
    fig, ax = plt.subplots(figsize=(7, 3.4))
    width = 0.24
    for k, (key, label) in enumerate(series):
        rows = h4[key]
        xs = [i + (k - 1) * width for i in range(len(rows))]
        est = [r["diff"]["estimate"] for r in rows]
        err = list(zip(*[_err(r["diff"]) for r in rows]))
        ax.bar(xs, est, width=width - 0.03, color=SERIES[k], label=label, edgecolor=SURFACE, linewidth=1)
        ax.errorbar(xs, est, yerr=err, fmt="none", ecolor=TEXT_2, elinewidth=1, capsize=2)
        for x, e in zip(xs, est):
            if e == 0:  # identical play: label it, or the empty slot reads as missing data
                ax.annotate("0", (x, 0), textcoords="offset points", xytext=(0, 4), ha="center", color=TEXT_2, fontsize=8)
    ax.axhline(0, color=TEXT_2, linewidth=1)
    values = [r["value"] for r in h4["eq_vs_fm"]]
    ax.set_xticks(range(len(values)), [f"V = {v:g}" for v in values])
    ax.set_ylabel("Mean payoff difference per encounter")
    ax.set_title("H4: per-encounter payoff difference by cell value (95% CI)")
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.12), ncol=3)
    ax.grid(axis="x", visible=False)
    path = out / "fig_h4_per_value.png"
    fig.savefig(path)
    plt.close(fig)
    return path


def fig_e2(results: Path, out: Path) -> Path:
    pairs = json.loads((results / "E2_summary.json").read_text(encoding="utf-8"))["pairings"]
    fig, ax = plt.subplots(figsize=(7, 2.6))
