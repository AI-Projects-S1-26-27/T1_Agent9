"""Build report/report.md from report/template.md and the result files.

Owner: Manas Tripathi, Reviewer: Jainam Parekh Naresh

The report template contains NO hand-typed results. It uses placeholders:

  {{value:FILE.path.to.field|FORMAT}}   a number or word from experiments/results/FILE.json
                                         (list items by index, e.g. pairs.0.p_deep_float);
                                         FORMAT is a Python format spec such as .3f or .1%
  {{table:NAME}}                         the generated table report/generated/NAME.md
  {{figure:FILE|caption}}                an image from report/figures
  {{check:FILE.path OP literal}}         a guard: OP in ==, !=, <, >, <=, >=

Every sentence in the narrative that depends on an outcome ("depth 5 does
worse than depth 3") is paired with a {{check:...}}. If a rerun ever
changed that outcome, the build FAILS and lists the stale sentences,
instead of silently publishing a narrative that no longer matches the data.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
TEMPLATE = ROOT / "report" / "template.md"
OUTPUT = ROOT / "report" / "report.md"
PLACEHOLDER = re.compile(r"\{\{(value|table|figure|check):([^}]*)\}\}")
CHECK = re.compile(r"^\s*([\w.\-]+)\s*(==|!=|<=|>=|<|>)\s*(.+?)\s*$")


class ReportError(RuntimeError):
    pass


def _lookup(results: Path, dotted: str) -> Any:
    file, _, path = dotted.partition(".")
    data: Any = json.loads((results / f"{file}.json").read_text(encoding="utf-8"))
    for part in path.split(".") if path else []:
        if isinstance(data, list):
            data = data[int(part)]
        elif isinstance(data, dict):
            if part not in data:
                raise ReportError(f"{dotted}: no key '{part}' (available: {sorted(data)[:12]})")
            data = data[part]
        else:
            raise ReportError(f"{dotted}: cannot index into {type(data).__name__}")
    return data


def _literal(text: str) -> Any:
    text = text.strip()
    if text in ("true", "True"):
        return True
    if text in ("false", "False"):
        return False
    try:
        return float(text)
    except ValueError:
        return text.strip("'\"")


def _compare(left: Any, op: str, right: Any) -> bool:
    if isinstance(right, float) and not isinstance(left, bool):
        left = float(left)
    return {
        "==": lambda: left == right,
        "!=": lambda: left != right,
        "<": lambda: left < right,
        ">": lambda: left > right,
        "<=": lambda: left <= right,
        ">=": lambda: left >= right,
    }[op]()


def render(template: str, results: Path, generated: Path) -> str:
    failures: list[str] = []

    def replace(match: re.Match) -> str:
        kind, body = match.group(1), match.group(2)
        if kind == "value":
            path, _, spec = body.partition("|")
            value = _lookup(results, path.strip())
            return format(value, spec) if spec else str(value)
        if kind == "table":
            return (generated / f"{body.strip()}.md").read_text(encoding="utf-8").strip()
        if kind == "figure":
            file, _, caption = body.partition("|")
            return f"![{caption.strip()}](figures/{file.strip()})\n\n*{caption.strip()}*"
        m = CHECK.match(body)
        if not m:
            raise ReportError(f"malformed check: {body}")
        left = _lookup(results, m.group(1))
        if not _compare(left, m.group(2), _literal(m.group(3))):
            failures.append(f"{body}  (actual: {left!r})")
        return ""

    text = PLACEHOLDER.sub(replace, template)
    if failures:
        raise ReportError("narrative no longer matches the data; update report/template.md:\n  " + "\n  ".join(failures))
    return text


def build_report(results: Path, generated: Path, template: Path = TEMPLATE, output: Path = OUTPUT) -> Path:
    banner = "<!-- GENERATED by `python -m resource_war.reproduce` from report/template.md. Do not edit this file; edit the template. -->\n\n"
    output.write_text(banner + render(template.read_text(encoding="utf-8"), results, generated), encoding="utf-8")
    print(f"report written to {output}")
    return output
